import fs from 'node:fs'
import path from 'node:path'

const rootDir = path.resolve(__dirname, '..', '..')

const colorLessPath = path.resolve(__dirname, 'lib/color.less')

const presetTypeOutputPath = path.resolve(rootDir, 'packages/miniprogram.shared/src/types/color.ts')

const colorUtilOutputPath = path.resolve(rootDir, 'packages/miniprogram.shared/src/core/util/color.ts')

const source = fs.readFileSync(colorLessPath, 'utf8')

/**
 * 解析 color.less：
 * @light-value: { base: #xxxxxx; }
 */
const colorMatches = [...source.matchAll(/@([a-z0-9-]+)-value:\s*\{\s*base:\s*(#[0-9a-fA-F]{3,8})\s*;/g)]

const colors = colorMatches.map((match) => ({
  name: match[1],
  base: match[2],
}))

if (!colors.length) {
  throw new Error('No preset colors found in color.less')
}

const colorNames = colors.map((item) => item.name)

/**
 * 生成文件头
 * - eslint-disable：避免 lint 干扰
 * - banner：禁止手动修改说明
 */
const GENERATED_BANNER = `/* eslint-disable */

/**
 * ------------------------------------------------------------------
 * ⚠️ AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * ------------------------------------------------------------------
 * This file is generated by:
 * packages/style/build.ts
 *
 * Any manual changes will be overwritten.
 * ------------------------------------------------------------------
 */
`

/**
 * types/color.ts
 */
const presetTypeContent = `${GENERATED_BANNER}
export type PresetColor =
  | ${colorNames.map((name) => `'${name}'`).join('\n  | ')}
`

/**
 * util/color.ts
 */
const colorUtilContent = `${GENERATED_BANNER}
import type { PresetColor } from '../../types'

const colors: { [key in PresetColor]: string } = {
${colors.map((c) => `  ${c.name}: '${c.base}',`).join('\n')}
}

export const isPresetColor = (color?: string): color is PresetColor => {
  return !!color && color in colors
}

export const getPresetColor = (color?: string): string => {
  return isPresetColor(color) ? colors[color as PresetColor] : color
}
`

/**
 * ensure dir
 */
fs.mkdirSync(path.dirname(presetTypeOutputPath), { recursive: true })
fs.mkdirSync(path.dirname(colorUtilOutputPath), { recursive: true })

/**
 * write files
 */
fs.writeFileSync(presetTypeOutputPath, presetTypeContent)
fs.writeFileSync(colorUtilOutputPath, colorUtilContent)

console.log('[build-color] done')
console.log(`- ${presetTypeOutputPath}`)
console.log(`- ${colorUtilOutputPath}`)
